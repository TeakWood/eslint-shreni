/**
 * @fileoverview Script to update the eslint:recommended configuration.
 * @author aladdin-add<weiran.zsd@outlook.com>
 */

"use strict";

//-----------------------------------------------------------------------------
// Requirements
//-----------------------------------------------------------------------------

const fs = require("node:fs");
const builtInRules = require("../lib/rules");

//------------------------------------------------------------------------------
// Helpers
//------------------------------------------------------------------------------

const recommendedRule = {};

for (const [ruleId, rule] of builtInRules) {
	if (!rule.meta.deprecated) {
		if (rule.meta.docs.recommended === true) {
			recommendedRule[ruleId] = "error";
		}
	}
}

const recommendedRulesText = JSON.stringify(
	recommendedRule,
	null,
	4,
).replaceAll("\n", "\n    ");

//-----------------------------------------------------------------------------
// Main
//-----------------------------------------------------------------------------

/*
 * The `// @ts-check` pragma has to be regenerated with the file: the config is
 * in the `tsconfig.json` allowlist, and `checkJs` is off, so the pragma — not
 * the allowlist — is what turns checking on. Dropping it here would leave the
 * file listed but unchecked, which `tests/lib/types/types.js` fails on.
 */
const code = `// @ts-check
/*
 * WARNING: This file is autogenerated using the tools/update-eslint-recommended.js
 * script. Do not edit manually.
 */

/*
 * Deliberately carries no \`@type\` annotation. The inferred type of this frozen
 * literal is the exact rule-name-to-severity map, which is what a TypeScript
 * config file wants for autocomplete; annotating it as a \`Config\` would widen
 * every rule name to \`string\` and would make \`@eslint/js\` depend on the
 * \`eslint\` package's declarations, which are an OPTIONAL peer dependency.
 */
"use strict";

module.exports = Object.freeze({
    name: "@eslint/js/recommended",
    rules: Object.freeze(${recommendedRulesText}),
});
`;

fs.writeFileSync(
	"./packages/js/src/configs/eslint-recommended.js",
	code,
	"utf8",
);
